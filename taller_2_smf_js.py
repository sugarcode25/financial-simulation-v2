def rename_fmp_columns(df, rename_map):
    """
    Renombra automáticamente columnas en df usando el mapa:
    clave deseada : lista de nombres alternativos.
    """
    for desired, alternatives in rename_map.items():
        if desired not in df.columns:
            for alt in alternatives:
                if alt in df.columns:
                    df.rename(columns={alt: desired}, inplace=True)
                    break
    return df

def get_fmp_financials(symbol, apikey="demo"):
    # Usamos los endpoints v4 que devuelven 'date' como clave
    bs_url = f"https://financialmodelingprep.com/api/v4/balance-sheet-statement?symbol={symbol}&limit=120&apikey={apikey}"
    is_url = f"https://financialmodelingprep.com/api/v4/income-statement?symbol={symbol}&limit=120&apikey={apikey}"

    # Balance Sheet
    bs_response = requests.get(bs_url)
    bs_data = bs_response.json()
    if isinstance(bs_data, dict):
        bs_data = [bs_data] if bs_data else []
    df_bs = pd.DataFrame(bs_data)

    # Income Statement
    is_response = requests.get(is_url)
    is_data = is_response.json()
    if isinstance(is_data, dict):
        is_data = [is_data] if is_data else []
    df_is = pd.DataFrame(is_data)

    # Si ambos están vacíos, se retorna DF vacío
    if df_bs.empty and df_is.empty:
        print("⚠️ No se combinaron datos FMP porque ambos DataFrames están vacíos.")
        return pd.DataFrame()

    # Renombrado automático: en API v4 se espera 'date', 'totalAssets', 'totalLiabilities', 'stockholdersEquity'
    rename_map_bs = {
        'date': ['fiscalDateEnding', 'reportedDate'],
        'totalAssets': ['assets'],
        'totalLiabilities': ['liabilities'],
        'stockholdersEquity': ['totalStockholdersEquity', 'equity']
    }
    rename_map_is = {
        'date': ['fiscalDateEnding', 'reportedDate'],
        'totalRevenue': ['revenue'],
        'netIncome': ['income']
    }
    if not df_bs.empty:
        df_bs = rename_fmp_columns(df_bs, rename_map_bs)
    if not df_is.empty:
        df_is = rename_fmp_columns(df_is, rename_map_is)

    # Si ambos DataFrames tienen la columna 'date', se realiza el merge; si no, se elige el no vacío
    if not df_bs.empty and not df_is.empty and 'date' in df_bs.columns and 'date' in df_is.columns:
        df_merged = pd.merge(df_bs, df_is, on='date', how='inner')
    elif not df_bs.empty:
        df_merged = df_bs.copy()
    elif not df_is.empty:
        df_merged = df_is.copy()
    else:
        print("⚠️ No se combinaron datos FMP porque el DF de FMP está vacío.")
        return pd.DataFrame()

    # Renombrar columnas para mayor claridad
    df_merged.rename(columns={
        'date': 'Date',
        'totalAssets': 'Total Assets',
        'totalLiabilities': 'Total Liabilities',
        'stockholdersEquity': 'Shareholder Equity',
        'totalRevenue': 'Total Revenue',
        'netIncome': 'Net Income'
    }, inplace=True)

    # Convertir la columna Date a datetime, eliminar filas sin fecha y ordenar
    if 'Date' in df_merged.columns:
        df_merged['Date'] = pd.to_datetime(df_merged['Date'], errors='coerce')
        df_merged.dropna(subset=['Date'], inplace=True)
        df_merged.sort_values(by='Date', ascending=False, inplace=True)

    df_merged['Company'] = symbol
    return df_merged

