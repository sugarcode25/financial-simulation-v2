prices = df['Close'].values.reshape(-1, 1)
look_back = 90  # número de días de contexto
train_size = int(len(prices) * 0.8)
train_values = prices[:train_size]
test_values  = prices[train_size:]

# Escalado lineal de los datos
min_price = float(train_values.min())
