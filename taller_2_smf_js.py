def get_value_from_row(row, default_keys, pattern):
    """Busca en la fila la primera clave disponible de la lista o que cumpla con el patrón."""
    for key in default_keys:
        if key in row.index and pd.notna(row[key]):
            return row[key]
    for key in row.index:
        if re.search(pattern, key, re.IGNORECASE) and pd.notna(row[key]):
            return row[key]
    return pd.NA

def get_combined_financial_data(ticker_obj, annual_attr, quarterly_attr):
    """Combina datos anuales y trimestrales evitando duplicados."""
    try:
        annual = getattr(ticker_obj, annual_attr)
        annual = annual.T if annual is not None else pd.DataFrame()
    except Exception:
        annual = pd.DataFrame()
    try:
        quarterly = getattr(ticker_obj, quarterly_attr)
        quarterly = quarterly.T if quarterly is not None else pd.DataFrame()
    except Exception:
        quarterly = pd.DataFrame()
    combined = pd.concat([annual, quarterly])
    combined = combined[~combined.index.duplicated(keep='first')]
    combined.sort_index(inplace=True)
    return combined

def get_financials_safe(ticker_obj, name):
    """Extrae los estados financieros (balance e income) usando yfinance."""
    bs = get_combined_financial_data(ticker_obj, 'balance_sheet', 'quarterly_balance_sheet')
    inc = get_combined_financial_data(ticker_obj, 'financials', 'quarterly_financials')

    df = pd.DataFrame({
        'Total Assets': bs.apply(lambda row: get_value_from_row(row, ['Total Assets'], r'asset'), axis=1),
        'Total Liabilities': bs.apply(lambda row: get_value_from_row(row, ['Total Liab', 'Total Liabilities'], r'liab'), axis=1),
        'Shareholder Equity': bs.apply(lambda row: get_value_from_row(row, ['Total Stockholder Equity', 'Total Equity'], r'equity'), axis=1),
        'Total Revenue': inc.apply(lambda row: get_value_from_row(row, ['Total Revenue'], r'revenue'), axis=1),
        'Net Income': inc.apply(lambda row: get_value_from_row(row, ['Net Income'], r'net income'), axis=1)
    })
    df.index.name = 'Date'
    df['Company'] = name
    return df.reset_index()

