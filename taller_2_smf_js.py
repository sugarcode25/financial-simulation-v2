# 6. Predicción a 30 días futuros mediante un método recursivo
def forecast_future(model, last_sequence, forecast_steps, look_back, min_val, max_val):
    """
    last_sequence: vector escalado de tamaño (look_back, 1) (últimos datos conocidos).
    forecast_steps: número de días a predecir.
    Se predice de forma recursiva.
    """
    forecast = []
    current_seq = last_sequence.copy()
    for _ in range(forecast_steps):
        current_seq_expanded = np.expand_dims(current_seq, axis=0)  # shape (1, look_back, 1)
        pred_scaled = model.predict(current_seq_expanded, verbose=0)[0][0]
        forecast.append(pred_scaled)
        # Actualizar la secuencia: eliminar el primer dato y agregar la predicción al final
        current_seq = np.vstack([current_seq[1:], [[pred_scaled]]])
    # Convertir predicciones a la escala original
    forecast_original = np.array(forecast) * (max_val - min_val) + min_val
    return forecast_original

