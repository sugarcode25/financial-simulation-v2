def get_fundamental_indicators(ticker_symbol):
    t = yf.Ticker(ticker_symbol)
    info = t.info

    # Fecha de hoy y hace 1 año (para calcular % cambio de precio)
    today = datetime.datetime.today()
    one_year_ago = today - datetime.timedelta(days=365)

    # Obtener precio actual (clave "currentPrice")
    current_price = info.get("currentPrice", np.nan)

    # Obtener el precio de hace 1 año
    try:
        hist = t.history(start=one_year_ago.strftime("%Y-%m-%d"), end=today.strftime("%Y-%m-%d"))
        if not hist.empty:
            price_1y = hist["Close"].iloc[0]
        else:
            price_1y = np.nan
    except Exception:
        price_1y = np.nan

    # Calcular cambio % en precio
    if not np.isnan(current_price) and not np.isnan(price_1y) and price_1y != 0:
        price_change_pct = ((current_price - price_1y) / price_1y) * 100
    else:
        price_change_pct = np.nan

    market_cap = info.get("marketCap", np.nan)
    pe_ratio = info.get("trailingPE", np.nan)

    # Antes teníamos "Cashflow"; ahora lo sustituimos por "DCF Valuation"
    dcf_val = calc_dcf_valuation(ticker_symbol)

    # Indicadores de rentabilidad
    roe = info.get("returnOnEquity", np.nan)
    roa = info.get("returnOnAssets", np.nan)
    eps = info.get("earningsPerShare", np.nan)

    # Indicadores de solvencia
    debt_to_equity = info.get("debtToEquity", np.nan)

    return {
        "Ticker": ticker_symbol,
        # Valoración
        "Current Price": current_price,
        "Price Change % (1Y)": price_change_pct,
        "Market Cap": market_cap,
        "P/E Ratio": pe_ratio,
        "DCF Valuation": dcf_val,  # Nuevo indicador en lugar de "Cashflow"
        # Rentabilidad
        "ROE": roe,
        "ROA": roa,
        "EPS": eps,
        # Solvencia
        "Debt-to-Equity": debt_to_equity
    }

