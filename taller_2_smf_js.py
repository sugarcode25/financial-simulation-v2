def proyectar_expansion(df, factor_activos=0.20, factor_revenue=0.10, factor_net_income=0.02):
    """
    Proyecta el comportamiento financiero ante una expansión mediante la adquisición de activos.

    Parámetros:
      - df: DataFrame con las columnas 'Total Assets', 'Total Liabilities',
            'Total Revenue' y 'Net Income'.
      - factor_activos: incremento porcentual de activos (y pasivos, si se financia con deuda).
      - factor_revenue: incremento porcentual en los ingresos.
      - factor_net_income: incremento porcentual en la utilidad neta.

    Retorna un DataFrame con las columnas proyectadas:
      'Projected Assets', 'Projected Liabilities', 'Projected Equity',
      'Projected Revenue' y 'Projected Net Income'.
    """
    df_proj = df.copy()
    df_proj["Projected Assets"] = df_proj["Total Assets"] * (1 + factor_activos)
    # Se asume que la adquisición se financia con deuda, incrementando pasivos en el mismo porcentaje.
    df_proj["Projected Liabilities"] = df_proj["Total Liabilities"] * (1 + factor_activos)
    df_proj["Projected Equity"] = df_proj["Projected Assets"] - df_proj["Projected Liabilities"]
    df_proj["Projected Revenue"] = df_proj["Total Revenue"] * (1 + factor_revenue)
    df_proj["Projected Net Income"] = df_proj["Net Income"] * (1 + factor_net_income)
    return df_proj

