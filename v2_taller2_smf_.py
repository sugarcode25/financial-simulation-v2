# %% [4] Extraer el año fiscal 2024 desde el reporte anual
# Saldos (activos, pasivos, patrimonio): valor al 31-dic-2024.
# Flujos (ingresos, utilidad): periodo de ~12 meses que termina el
# 31-dic-2024. Así C y NU quedan en el MISMO periodo (corrige N5).
import pandas as pd

FORMULARIO = {'C': '10-K', 'NU': '20-F'}
CIERRE = '2024-12-31'

def valor(tk, tags, es_flujo):
    """Busca la primera etiqueta disponible y devuelve (valor, etiqueta, formulario, fecha de radicación)."""
    for tax, datos in facts[tk]['facts'].items():
        for t in tags:
            if t not in datos:
                continue
            # Tomamos las unidades en USD (si no hay USD, avisamos)
            unidades = datos[t]['units']
            if 'USD' not in unidades:
                print(f'⚠️ {tk} {t}: no está en USD, unidades = {list(unidades)}')
                continue
            df = pd.DataFrame(unidades['USD'])
            df = df[(df['end'] == CIERRE) & (df['form'] == FORMULARIO[tk]) & (df['fy'] == 2024)]
            if es_flujo:
                dias = (pd.to_datetime(df['end']) - pd.to_datetime(df['start'])).dt.days
                df = df[dias.between(350, 380)]          # solo periodos anuales
            if df.empty:
                continue
            fila = df.sort_values('filed').iloc[-1]      # la radicación más reciente
            return fila['val'], f'{tax}:{t}', fila['form'], fila['filed']
    return None, 'NO ENCONTRADO', None, None

