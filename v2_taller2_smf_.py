# %% [P3-3] Monte Carlo 100/200/300 con semilla fija y SIN el error de indexación de la v1
def simular(n, mu, cov, rf, rng):
    """n portafolios aleatorios sin cortos. Pesos Dirichlet(1,1,1) = uniformes sobre todas las combinaciones."""
    W = rng.dirichlet(np.ones(len(mu)), size=n)
    r = W @ mu.values
    v = np.sqrt(np.einsum('ij,jk,ik->i', W, cov.values, W))
    s = (r - rf) / v
    return W, r, v, s

SEMILLA = 42
filas = []
for rf_nombre, rf in [('rf = T-bill', RF), ('rf = 0 (como la v1)', 0.0)]:
    if rf is None:
        continue
    for n in [100, 200, 300]:
        rng = np.random.default_rng(SEMILLA + n)   # una semilla distinta por tamaño: corridas independientes, como en el curso
        W, r, v, s = simular(n, mu, cov, rf, rng)
        i = np.argmax(s)                          # CORRECCIÓN: índice tomado sobre el MISMO arreglo de los pesos
        filas.append({'Tasa': rf_nombre, 'Simulaciones': n, 'Retorno': r[i], 'Volatilidad': v[i], 'Sharpe': s[i],
                      **{f'w_{a}': W[i, k] for k, a in enumerate(ACTIVOS)}})
