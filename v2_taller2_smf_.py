# %% [P3-5] Extensión propia: solución EXACTA (optimizador) para comparar con el Monte Carlo
from scipy.optimize import minimize

def optimo(objetivo):
    n = len(mu)
    res = minimize(objetivo, np.ones(n) / n, method='SLSQP', bounds=[(0, 1)] * n,
                   constraints=[{'type': 'eq', 'fun': lambda w: w.sum() - 1}])
    return res.x

